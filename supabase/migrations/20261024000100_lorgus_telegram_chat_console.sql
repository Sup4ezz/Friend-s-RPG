create table if not exists public.lorgus_telegram_chats (
  chat_id text primary key,
  title text not null,
  chat_type text not null,
  username text,
  last_message_at timestamptz,
  updated_at timestamptz not null default now()
);
create table if not exists public.lorgus_telegram_messages (
  id bigint generated by default as identity primary key,
  chat_id text not null references public.lorgus_telegram_chats(chat_id) on delete cascade,
  message_id bigint not null,
  thread_id bigint,
  topic_title text,
  sender_id text,
  sender_name text not null default 'Неизвестно',
  text text not null default '',
  sent_at timestamptz not null,
  is_outgoing boolean not null default false,
  unique(chat_id, message_id)
);
create index if not exists lorgus_telegram_messages_chat_date_idx on public.lorgus_telegram_messages(chat_id, sent_at desc);
create index if not exists lorgus_telegram_messages_thread_idx on public.lorgus_telegram_messages(chat_id, thread_id, sent_at desc);
alter table public.lorgus_telegram_chats enable row level security;
alter table public.lorgus_telegram_messages enable row level security;
revoke all on public.lorgus_telegram_chats from anon, authenticated;
revoke all on public.lorgus_telegram_messages from anon, authenticated;
grant all on public.lorgus_telegram_chats to service_role;
grant all on public.lorgus_telegram_messages to service_role;
grant usage, select on sequence public.lorgus_telegram_messages_id_seq to service_role;